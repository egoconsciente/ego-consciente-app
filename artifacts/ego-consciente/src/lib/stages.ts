export const STAGES: StageDefinition[] = STAGE_DATA.map((s) => ({
  ...s,
  phase: getPhase(s.stageNumber),
}));

export const TOTAL_STAGES = 40;

export function getStage(stageNumber: number): StageDefinition | undefined {
  return STAGES.find((s) => s.stageNumber === stageNumber);
}

export function getPhaseForStage(stageNumber: number): { name: string; start: number; end: number } {
  return PHASES.find((p) => stageNumber >= p.start && stageNumber <= p.end) || PHASES[0];
}

export function isPhaseStart(stageNumber: number): boolean {
  return PHASES.some((p) => p.start === stageNumber);
}

